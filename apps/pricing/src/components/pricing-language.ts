// Like landing, translate text nodes without replacing the React-owned elements.
export function observePricingLanguage(language: string) {
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  const originals = new Map<Text, { source: string; rendered: string }>();
  const roots = Array.from(document.querySelectorAll("main, .skip-link"));
  const observer = new MutationObserver(translate);
  function translate() {
    observer.disconnect();
    for (const root of roots) {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node: Node | null;
      while ((node = walker.nextNode())) {
        const text = node as Text;
        const previous = originals.get(text);
        const source = previous && text.data === previous.rendered ? previous.source : text.data;
        const key = source.trim().replace(/\s+/g, " ");
        const translated = language === "zh" ? chinese[key] : undefined;
        const rendered = translated ? source.replace(/\S[\s\S]*\S|\S/, translated) : source;
        originals.set(text, { source, rendered });
        if (text.data !== rendered) text.data = rendered;
      }
    }
    const emailInput = document.querySelector<HTMLInputElement>('.final-cta-email input[type="email"]');
    if (emailInput) emailInput.placeholder = language === "zh" ? chinese["Work email"] : "Work email";
    roots.forEach(root => observer.observe(root, { childList: true, characterData: true, subtree: true }));
  }
  translate();
  return () => {
    observer.disconnect();
    originals.forEach(({ source, rendered }, node) => { if (node.isConnected && node.data === rendered) node.data = source; });
  };
}
